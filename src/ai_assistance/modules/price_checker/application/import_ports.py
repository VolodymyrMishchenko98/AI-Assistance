from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable, Protocol
from uuid import UUID

from .imports import ImportPreviewDto, ImportRowDto, ImportSheetDto


@dataclass(frozen=True, slots=True)
class WorkbookRow:
    excel_row_number: int
    values: dict[str, Any]
    formula_fields: frozenset[str]


class XlsxReader(Protocol):
    def list_sheets(self, path: Path) -> tuple[ImportSheetDto, ...]: ...
    def iter_rows(self, path: Path, sheet: str, header_row: int, mapping: dict[str, str]) -> Iterable[WorkbookRow]: ...


class ImportPreviewRepository(Protocol):
    def create(self, preview: ImportPreviewDto) -> None: ...
    def get(self, preview_id: UUID) -> ImportPreviewDto | None: ...
    def get_for_run(self, preview_id: UUID, run_id: UUID) -> ImportPreviewDto | None: ...
    def find_by_key(self, run_id: UUID, idempotency_key: str) -> ImportPreviewDto | None: ...
    def update_row(self, preview_id: UUID, row: ImportRowDto, expires_at: Any, now: Any) -> bool: ...
    def exclude_row(self, preview_id: UUID, row_id: UUID, expires_at: Any, now: Any) -> bool: ...
    def save_final_fingerprint(self, preview_id: UUID, fingerprint: str, now: Any) -> bool: ...
    def mark_confirmed(self, preview_id: UUID, item_ids: tuple[UUID, ...], when: Any, final_fingerprint: str) -> bool: ...
    def delete_expired(self, now: Any) -> int: ...
